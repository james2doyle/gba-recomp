//! Links the system SDL3 library (SPEC-061 FE-61-01). No crates.io
//! dependency: the FFI surface is declared by hand in `src/sdl.rs`.
//! `SDL3_LIB_DIR` overrides the library search path.
//!
//! Emscripten (SPEC-068 Web): SDL3 comes from the Emscripten port
//! (`emcc --use-port=sdl3`) at the final link, so no host search path or
//! library is added here.
//!
//! It also turns `assets/fonts/PixAntiqua.ttf` into a 12 px glyph atlas
//! (SPEC-069 L10N-69-05). The font is a bitmap design: every contour is made
//! of axis-aligned rectangles whose coordinates land exactly on the 12 px
//! grid, so rasterizing here is exact and the frontend needs no font library
//! — which is what keeps SDL_ttf out of the five platform bundles.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-env-changed=SDL3_LIB_DIR");
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let font = manifest.join("../../assets/fonts/PixAntiqua.ttf");
    println!("cargo:rerun-if-changed={}", font.display());
    build_atlas(&font).expect("build the glyph atlas");

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    if target_os == "emscripten" {
        return;
    }
    let dir = env::var("SDL3_LIB_DIR")
        .ok()
        .or_else(|| (target_os == "macos").then(|| "/opt/homebrew/lib".to_owned()));
    if let Some(dir) = dir {
        println!("cargo:rustc-link-search=native={dir}");
    }
    println!("cargo:rustc-link-lib=dylib=SDL3");
}

// ------------------------------------------------------------------- atlas

/// Em size the frontend draws at. The font is designed for exactly this.
const SIZE: f32 = 12.0;

/// A glyph placed in the atlas.
struct Glyph {
    code: u32,
    advance: u32,
    /// Atlas position and size, in pixels.
    x: u32,
    y: u32,
    w: u32,
    h: u32,
    /// Rows between the top of the line box and the first inked row, so the
    /// renderer can place the cropped bitmap back on its baseline.
    oy: u32,
    /// Columns between the pen origin and the first inked column. Signed:
    /// ink can start left of the pen (`j`'s hook reaches x = -2 px), and
    /// cropping it away would amputate the glyph.
    ox: i32,
}

fn build_atlas(path: &std::path::Path) -> Result<(), String> {
    let data = fs::read(path).map_err(|e| format!("cannot read {}: {e}", path.display()))?;
    let face = Face::parse(&data)?;

    // Every codepoint the font covers, in order, so the atlas is stable.
    let cmap = face.cmap()?;
    let mut glyphs = Vec::new();
    let mut bitmaps: BTreeMap<u32, Vec<Vec<bool>>> = BTreeMap::new();
    for (&code, &gid) in &cmap {
        let (advance, outline) = face.glyph(gid)?;
        let (bitmap, oy, ox) =
            rasterize(&outline, SIZE).map_err(|e| format!("U+{code:04X}: {e}"))?;
        bitmaps.insert(code, bitmap);
        glyphs.push(Glyph {
            code,
            advance,
            x: 0,
            y: 0,
            w: 0,
            h: 0,
            oy,
            ox,
        });
    }

    // Shelf packing: widest glyphs first keeps rows compact.
    const PAD: u32 = 1;
    const ATLAS_W: u32 = 256;
    let mut order: Vec<usize> = (0..glyphs.len()).collect();
    order.sort_by_key(|&i| {
        let b = &bitmaps[&glyphs[i].code];
        (
            std::cmp::Reverse(b.first().map_or(0, Vec::len)),
            glyphs[i].code,
        )
    });
    let (mut pen_x, mut pen_y, mut shelf_h) = (0u32, 0u32, 0u32);
    for &i in &order {
        let b = &bitmaps[&glyphs[i].code];
        let (w, h) = (b.first().map_or(0, Vec::len) as u32, b.len() as u32);
        if w == 0 || h == 0 {
            continue;
        }
        if pen_x + w > ATLAS_W {
            pen_x = 0;
            pen_y += shelf_h + PAD;
            shelf_h = 0;
        }
        glyphs[i].x = pen_x;
        glyphs[i].y = pen_y;
        glyphs[i].w = w;
        glyphs[i].h = h;
        pen_x += w + PAD;
        shelf_h = shelf_h.max(h);
    }
    let atlas_h = (pen_y + shelf_h).max(1);

    // Ink coverage: 255 where a pixel is set, 0 elsewhere.
    let mut pixels = vec![0u8; (ATLAS_W * atlas_h) as usize];
    for g in &glyphs {
        let b = &bitmaps[&g.code];
        for (row, line) in b.iter().enumerate() {
            for (col, &on) in line.iter().enumerate() {
                if on {
                    let at = (g.y + row as u32) * ATLAS_W + g.x + col as u32;
                    pixels[at as usize] = 255;
                }
            }
        }
    }

    let mut out = String::new();
    out.push_str("// @generated by build.rs from assets/fonts/PixAntiqua.ttf.\n");
    out.push_str("// PixAntiqua (c) 2008 Gerhard Grossmann, SIL OFL 1.1.\n");
    out.push_str("// Do not edit; change the font or build.rs instead.\n\n");
    // Always emit a float literal: `12` alone would be an integer.
    let _ = writeln!(out, "pub const SIZE: f32 = {SIZE:.1};");
    let _ = writeln!(out, "pub const WIDTH: u32 = {ATLAS_W};");
    let _ = writeln!(out, "pub const HEIGHT: u32 = {atlas_h};");
    let _ = writeln!(
        out,
        "pub const ADVANCE_SPACE: u32 = {};",
        space_advance(&glyphs)
    );
    out.push_str("\npub static COVERAGE: [u8; ");
    let _ = writeln!(out, "{}] = [", pixels.len());
    for chunk in pixels.chunks(32) {
        out.push_str("    ");
        for &p in chunk {
            let _ = write!(out, "{p},");
        }
        out.push('\n');
    }
    out.push_str("];\n\n");
    out.push_str(
        "/// (code point, advance, atlas x, atlas y, width, height, top offset, left offset).\n",
    );
    out.push_str("pub type GlyphRow = (u32, u8, u16, u16, u8, u8, u8, i8);\n");
    out.push_str("pub static GLYPHS: &[GlyphRow] = &[\n");
    for g in &glyphs {
        let _ = writeln!(
            out,
            "    (0x{:04X}, {}, {}, {}, {}, {}, {}, {}),",
            g.code, g.advance, g.x, g.y, g.w, g.h, g.oy, g.ox
        );
    }
    out.push_str("];\n");

    let dest = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("font_atlas.rs");
    fs::write(&dest, out).map_err(|e| format!("cannot write {}: {e}", dest.display()))?;
    println!(
        "cargo:warning=glyph atlas: {} glyphs, {ATLAS_W}x{atlas_h}",
        glyphs.len()
    );
    Ok(())
}

fn space_advance(glyphs: &[Glyph]) -> u32 {
    glyphs
        .iter()
        .find(|g| g.code == ' ' as u32)
        .map_or(3, |g| g.advance)
}

/// Turns contours into a 1-bit bitmap for the line box at `size` px.
///
/// Returns rows top-down plus the ink box offset: `oy` from the top of the
/// line box, `ox` from the pen origin (signed — `j`'s hook starts left of
/// the pen and must survive the crop). Empty for glyphs without ink (space).
fn rasterize(outline: &Outline, size: f32) -> Result<(Vec<Vec<bool>>, u32, i32), String> {
    if outline.contours.is_empty() {
        return Ok((Vec::new(), 0, 0));
    }
    let scale = size / f32::from(outline.units_per_em);
    let ascent = outline.ascent as f32;
    // Pixel-space position of a font unit: x keeps its origin, y is measured
    // down from the top of the line box.
    let to_px_x = |ux: f32| ux * scale;
    let to_px_y = |uy: f32| (ascent - uy) * scale;

    // Edges keep their direction: the nonzero winding rule needs it to know
    // which crossings open a span and which close one.
    let mut edges: Vec<(f32, f32, f32, f32)> = Vec::new();
    for contour in &outline.contours {
        for i in 0..contour.len() {
            let (x0, y0) = contour[i];
            let (x1, y1) = contour[(i + 1) % contour.len()];
            let (px0, py0) = (to_px_x(x0), to_px_y(y0));
            let (px1, py1) = (to_px_x(x1), to_px_y(y1));
            if (py0 - py1).abs() < f32::EPSILON {
                continue; // horizontal edges never cross a scanline
            }
            edges.push((px0, py0, px1, py1));
        }
    }

    let line_h = ((outline.ascent - outline.descent) as f32 * scale).round() as u32;
    let mut rows = Vec::new();
    let mut min_x = i32::MAX;
    let mut max_x = i32::MIN;
    for row in 0..line_h {
        let y = row as f32 + 0.5;
        // A downward edge (y increasing, y-down space) enters the fill;
        // an upward edge leaves it.
        let mut hits: Vec<(f32, i32)> = edges
            .iter()
            .filter(|&&(_, y0, _, y1)| {
                let (lo, hi) = if y0 < y1 { (y0, y1) } else { (y1, y0) };
                y >= lo && y < hi
            })
            .map(|&(x0, y0, x1, y1)| {
                let t = (y - y0) / (y1 - y0);
                let x = x0 + (x1 - x0) * t;
                (x, if y1 > y0 { 1 } else { -1 })
            })
            .collect();
        hits.sort_by(|a, b| a.0.partial_cmp(&b.0).unwrap_or(std::cmp::Ordering::Equal));
        let mut spans: Vec<(i32, i32)> = Vec::new();
        let mut winding = 0;
        let mut start = 0f32;
        for (x, dir) in hits {
            if winding == 0 {
                start = x;
            }
            winding += dir;
            if winding == 0 {
                // Signed: ink left of the pen origin is real ink (`j`'s hook)
                // and clamping it to x >= 0 amputated the glyph.
                let a = start.round() as i32;
                let b = x.round() as i32;
                if b > a {
                    min_x = min_x.min(a);
                    max_x = max_x.max(b);
                    spans.push((a, b));
                }
            }
        }
        rows.push(spans);
    }

    if min_x == i32::MAX {
        return Ok((Vec::new(), 0, 0));
    }
    // Crop to the ink box on both axes so the atlas stays tight and the
    // glyph origin is the top-left of its ink.
    let left = min_x;
    let width = max_x - left;
    let mut full = vec![vec![false; width as usize]; rows.len()];
    for (y, spans) in rows.iter().enumerate() {
        for &(a, b) in spans {
            for x in a..b {
                full[y][(x - left) as usize] = true;
            }
        }
    }
    let blank = |row: &Vec<bool>| row.iter().all(|&on| !on);
    let top = full.iter().position(|r| !blank(r)).unwrap_or(0);
    let bottom = full.iter().rposition(|r| !blank(r)).unwrap_or(0) + 1;
    Ok((full[top..bottom].to_vec(), top as u32, left))
}

// -------------------------------------------------------------- ttf reader

struct Outline {
    units_per_em: u16,
    ascent: i16,
    descent: i16,
    /// Each contour is a closed list of on-curve points.
    contours: Vec<Vec<(f32, f32)>>,
}

struct Face<'a> {
    data: &'a [u8],
    tables: BTreeMap<[u8; 4], (usize, usize)>,
}

impl<'a> Face<'a> {
    fn parse(data: &'a [u8]) -> Result<Self, String> {
        if data.len() < 12 {
            return Err("font shorter than a table directory".into());
        }
        let num = be16(data, 4)? as usize;
        let mut tables = BTreeMap::new();
        for i in 0..num {
            let at = 12 + i * 16;
            let tag = [
                *data.get(at).ok_or("truncated table tag")?,
                *data.get(at + 1).ok_or("truncated table tag")?,
                *data.get(at + 2).ok_or("truncated table tag")?,
                *data.get(at + 3).ok_or("truncated table tag")?,
            ];
            let off = be32(data, at + 8)? as usize;
            let len = be32(data, at + 12)? as usize;
            tables.insert(tag, (off, len));
        }
        Ok(Self { data, tables })
    }

    fn table(&self, tag: &[u8; 4]) -> Result<(usize, usize), String> {
        self.tables
            .get(tag)
            .copied()
            .ok_or_else(|| format!("missing `{}` table", String::from_utf8_lossy(tag)))
    }

    fn u16_at(&self, at: usize) -> Result<u16, String> {
        be16(self.data, at)
    }

    /// `cmap` format 4 → codepoint to glyph id.
    fn cmap(&self) -> Result<BTreeMap<u32, u16>, String> {
        let (base, _) = self.table(b"cmap")?;
        let count = self.u16_at(base + 2)? as usize;
        let mut chosen = None;
        for i in 0..count {
            let rec = base + 4 + i * 8;
            let (pid, eid) = (self.u16_at(rec)?, self.u16_at(rec + 2)?);
            let off = be32(self.data, rec + 4)? as usize;
            let sub = base + off;
            let format = self.u16_at(sub)?;
            let unicode = pid == 0 || (pid == 3 && matches!(eid, 1 | 10));
            if unicode && format == 4 {
                chosen = Some(sub);
                break;
            }
        }
        let sub = chosen.ok_or("no Unicode format 4 cmap subtable")?;
        let seg_x2 = self.u16_at(sub + 6)? as usize;
        let segs = seg_x2 / 2;
        let ends = sub + 14;
        let starts = ends + seg_x2 + 2;
        let deltas = starts + seg_x2;
        let range_offsets = deltas + seg_x2;
        let mut map = BTreeMap::new();
        for s in 0..segs {
            let end = self.u16_at(ends + s * 2)?;
            let start = self.u16_at(starts + s * 2)?;
            let delta = self.u16_at(deltas + s * 2)? as i32;
            let range_at = range_offsets + s * 2;
            let range = self.u16_at(range_at)? as usize;
            if start > end || start == 0xFFFF {
                continue;
            }
            for code in start..=end {
                let gid = if range == 0 {
                    (code as i32 + delta) as u16
                } else {
                    let at = range_at + range + (code - start) as usize * 2;
                    let g = self.u16_at(at)?;
                    if g == 0 { 0 } else { (g as i32 + delta) as u16 }
                };
                if gid != 0 {
                    map.insert(u32::from(code), gid);
                }
            }
        }
        Ok(map)
    }

    /// Advance width and contours for a glyph id.
    fn glyph(&self, gid: u16) -> Result<(u32, Outline), String> {
        let (head, _) = self.table(b"head")?;
        let units_per_em = self.u16_at(head + 18)?;
        let loc_format = self.u16_at(head + 50)?;
        let (hhea, _) = self.table(b"hhea")?;
        let ascent = self.u16_at(hhea + 4)? as i16;
        let descent = self.u16_at(hhea + 6)? as i16;
        let metrics = self.u16_at(hhea + 34)? as usize;
        let (loca, _) = self.table(b"loca")?;
        let (glyf, _) = self.table(b"glyf")?;
        let (hmtx, _) = self.table(b"hmtx")?;

        let (start, end) = if loc_format == 0 {
            (
                self.u16_at(loca + gid as usize * 2)? as usize * 2,
                self.u16_at(loca + gid as usize * 2 + 2)? as usize * 2,
            )
        } else {
            (
                be32(self.data, loca + gid as usize * 4)? as usize,
                be32(self.data, loca + gid as usize * 4 + 4)? as usize,
            )
        };
        // Advance: the last entry repeats for glyphs past numberOfHMetrics.
        let idx = (gid as usize).min(metrics.saturating_sub(1));
        let advance = self.u16_at(hmtx + idx * 4)? as u32;
        let scale = SIZE / f32::from(units_per_em);
        let advance_px = (f32::from(advance as u16) * scale).round() as u32;

        let mut outline = Outline {
            units_per_em,
            ascent,
            descent,
            contours: Vec::new(),
        };
        if end <= start {
            return Ok((advance_px, outline));
        }
        let at = glyf + start;
        let ncontours = self.u16_at(at)? as i16;
        if ncontours < 0 {
            return Err("composite glyphs are not supported".into());
        }
        let ncontours = ncontours as usize;
        let mut cursor = at + 10;
        let mut end_pts = Vec::with_capacity(ncontours);
        for _ in 0..ncontours {
            end_pts.push(self.u16_at(cursor)? as usize);
            cursor += 2;
        }
        let instructions = self.u16_at(cursor)? as usize;
        cursor += 2 + instructions;
        let points = end_pts.last().map_or(0, |e| e + 1);
        let mut flags = Vec::with_capacity(points);
        while flags.len() < points {
            let f = *self.data.get(cursor).ok_or("truncated glyph flags")?;
            cursor += 1;
            flags.push(f);
            if f & 0x08 != 0 {
                let repeat = *self.data.get(cursor).ok_or("truncated repeat count")?;
                cursor += 1;
                for _ in 0..repeat {
                    flags.push(f);
                }
            }
        }
        flags.truncate(points);
        let mut xs = Vec::with_capacity(points);
        let mut v = 0i32;
        for &f in &flags {
            if f & 0x02 != 0 {
                let d = *self.data.get(cursor).ok_or("truncated x delta")? as i32;
                cursor += 1;
                v += if f & 0x10 != 0 { d } else { -d };
            } else if f & 0x10 == 0 {
                v += i32::from(self.u16_at(cursor)? as i16);
                cursor += 2;
            }
            xs.push(v);
        }
        let mut ys = Vec::with_capacity(points);
        let mut v = 0i32;
        for &f in &flags {
            if f & 0x04 != 0 {
                let d = *self.data.get(cursor).ok_or("truncated y delta")? as i32;
                cursor += 1;
                v += if f & 0x20 != 0 { d } else { -d };
            } else if f & 0x20 == 0 {
                v += i32::from(self.u16_at(cursor)? as i16);
                cursor += 2;
            }
            ys.push(v);
        }

        // The atlas assumes a rectilinear outline; a curve would need
        // flattening, so refuse it instead of drawing something wrong.
        let mut first = 0;
        for &last in &end_pts {
            let mut contour = Vec::with_capacity(last + 1 - first);
            for i in first..=last {
                if flags[i] & 0x01 == 0 {
                    return Err(format!(
                        "glyph {gid} has an off-curve point; the atlas needs a bitmap font"
                    ));
                }
                contour.push((xs[i] as f32, ys[i] as f32));
            }
            if contour.len() >= 2 {
                // Coordinates must land on whole pixels, or the 1-bit
                // result would be a guess.
                for &(x, y) in &contour {
                    for value in [(x * scale).abs(), ((ascent as f32 - y) * scale).abs()] {
                        if (value - value.round()).abs() > 0.05 {
                            return Err(format!(
                                "glyph {gid} is not pixel-aligned at {SIZE} px ({value})"
                            ));
                        }
                    }
                }
                outline.contours.push(contour);
            }
            first = last + 1;
        }
        Ok((advance_px, outline))
    }
}

fn be16(data: &[u8], at: usize) -> Result<u16, String> {
    let b = data.get(at..at + 2).ok_or("read past end of font")?;
    Ok(u16::from_be_bytes([b[0], b[1]]))
}

fn be32(data: &[u8], at: usize) -> Result<u32, String> {
    let b = data.get(at..at + 4).ok_or("read past end of font")?;
    Ok(u32::from_be_bytes([b[0], b[1], b[2], b[3]]))
}
